BEGIN;

-- ------------------------------------------------------------------------------
-- 1. BASELINE TABLE DEFINITION: public.guests
-- ------------------------------------------------------------------------------
-- Replicates the exact verified Production baseline column order, data types,
-- nullability, and default expressions.
-- Column Order (1-9):
--   1. id               (uuid, PK, default gen_random_uuid(), NOT NULL)
--   2. guest_name       (text, default ''::text, NOT NULL)
--   3. invitation_token (text, default ''::text, nullable, no DEFAULT NULL)
--   4. rsvp_status      (text, default 'pending'::text, nullable)
--   5. rsvp_message     (text, default ''::text, nullable)
--   6. responded_at     (timestamptz, no default, nullable)
--   7. created_at       (timestamptz, default now(), nullable)
--   8. updated_at       (timestamptz, default now(), nullable)
--   9. invitation_slug  (text, no default, nullable)
--
-- Table-level constraint:
--   - guests_invitation_token_unique: UNIQUE constraint on (invitation_token)
-- Fail-closed: plain CREATE TABLE fails if table already exists.
-- ------------------------------------------------------------------------------
CREATE TABLE public.guests (
  -- 1. Primary key UUID generated by pg_catalog.gen_random_uuid()
  id uuid PRIMARY KEY DEFAULT pg_catalog.gen_random_uuid(),

  -- 2. Guest name (Khmer / Latin): baseline NOT NULL with empty string default
  guest_name text NOT NULL DEFAULT ''::text,

  -- 3. Legacy invitation token: baseline default is empty string
  invitation_token text DEFAULT ''::text,

  -- 4. RSVP status: baseline default is 'pending'
  rsvp_status text DEFAULT 'pending'::text,

  -- 5. RSVP blessing / note: baseline default is empty string
  rsvp_message text DEFAULT ''::text,

  -- 6. Timestamp when RSVP was submitted: no default (pg_attrdef has no entry)
  responded_at timestamptz,

  -- 7. Timestamp when guest was created: default now()
  created_at timestamptz DEFAULT pg_catalog.now(),

  -- 8. Timestamp when guest was last updated: default now()
  updated_at timestamptz DEFAULT pg_catalog.now(),

  -- 9. Unique URL invitation slug: no default (pg_attrdef has no entry)
  invitation_slug text,

  -- Baseline UNIQUE table constraint on invitation_token
  CONSTRAINT guests_invitation_token_unique UNIQUE (invitation_token)
);

-- Ensure standard administrative table ownership
ALTER TABLE public.guests OWNER TO postgres;

-- ------------------------------------------------------------------------------
-- 2. PRODUCTION BASELINE PARTIAL UNIQUE INDEX ON INVITATION_SLUG
-- ------------------------------------------------------------------------------
-- In Production baseline, guests_invitation_slug_unique is a standalone partial
-- unique index filtering out NULL slugs.
-- Fail-closed: plain CREATE UNIQUE INDEX fails if index already exists.
-- NOTE: guests_invitation_slug_lower_idx is deliberately NOT created here;
--       that case-insensitive expression index is created by slug_only_security_migration.sql.
-- ------------------------------------------------------------------------------
CREATE UNIQUE INDEX guests_invitation_slug_unique
  ON public.guests (invitation_slug)
  WHERE invitation_slug IS NOT NULL;

-- ------------------------------------------------------------------------------
-- 3. ROW LEVEL SECURITY (RLS) & STRICT ADMIN ACCESS POLICY
-- ------------------------------------------------------------------------------
-- Enables RLS immediately to prevent open data exposure.
-- CRITICAL SECURITY RULES:
-- - NEVER use permissive USING (true) for authenticated users.
-- - Table CRUD is strictly restricted to authorized wedding administrators
--   via trusted JWT claims: lower(email) = 'admin@invitation.com' or app_metadata.role = 'admin'.
-- - user_metadata is intentionally omitted because it is client-writable.
-- - Fresh staging project has zero tables in public; DROP POLICY is omitted.
-- - Matches Runbook Section 4 verification query expectations character-for-character.
-- ------------------------------------------------------------------------------
ALTER TABLE public.guests ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Authenticated admins can manage guests"
  ON public.guests
  FOR ALL
  TO authenticated
  USING (
    (pg_catalog.lower((auth.jwt() ->> 'email'::text)) = 'admin@invitation.com'::text)
    OR (((auth.jwt() -> 'app_metadata'::text) ->> 'role'::text) = 'admin'::text)
  )
  WITH CHECK (
    (pg_catalog.lower((auth.jwt() ->> 'email'::text)) = 'admin@invitation.com'::text)
    OR (((auth.jwt() -> 'app_metadata'::text) ->> 'role'::text) = 'admin'::text)
  );

-- ------------------------------------------------------------------------------
-- 4. TABLE PRIVILEGES (GRANTS & REVOKES - PRODUCTION BASELINE FIDELITY)
-- ------------------------------------------------------------------------------
-- - Revoke ALL direct table permissions from anon and PUBLIC.
--   Public users must access invitations exclusively through SECURITY DEFINER RPCs.
-- - Grant strictly CRUD permissions (SELECT, INSERT, UPDATE, DELETE) to authenticated.
-- - Revoke dangerous non-CRUD privileges (TRUNCATE, REFERENCES, TRIGGER) from authenticated.
-- - On PostgreSQL 17+, revoke MAINTAIN from authenticated.
-- - service_role baseline: grant REFERENCES, TRIGGER, TRUNCATE to mirror known
--   Production baseline audit (service_role had no direct CRUD table grants).
-- ------------------------------------------------------------------------------
REVOKE ALL ON TABLE public.guests FROM anon, PUBLIC;

GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.guests TO authenticated;
REVOKE TRUNCATE, REFERENCES, TRIGGER ON TABLE public.guests FROM authenticated;

-- On PostgreSQL 17+, also revoke MAINTAIN if granted to authenticated
DO $$
BEGIN
  IF current_setting('server_version_num')::int >= 170000 THEN
    EXECUTE 'REVOKE MAINTAIN ON TABLE public.guests FROM authenticated;';
  END IF;
END $$;

-- Align service_role privileges strictly with Production baseline audit
GRANT REFERENCES, TRIGGER, TRUNCATE ON TABLE public.guests TO service_role;

-- ------------------------------------------------------------------------------
-- 5. REPLICA IDENTITY (FOR SUPABASE REALTIME SUPPORT)
-- ------------------------------------------------------------------------------
-- Ensures UPDATE and DELETE events include full previous row data for admin UI sync.
ALTER TABLE public.guests REPLICA IDENTITY FULL;

COMMIT;
